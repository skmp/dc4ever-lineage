"""What counts as source, what is vendored. Edit here; count.py and snapshot.py import it."""
import re
EXT = {
 '.c':'C', '.h':'C/C++ header', '.hpp':'C/C++ header', '.hh':'C/C++ header', '.hxx':'C/C++ header', '.inl':'C/C++ header',
 '.cpp':'C++', '.cc':'C++', '.cxx':'C++',
 '.cs':'C#',
 '.s':'Assembly', '.S':'Assembly', '.asm':'Assembly',
 '.glsl':'Shader', '.vert':'Shader', '.frag':'Shader', '.vs':'Shader', '.ps':'Shader', '.fs':'Shader', '.fx':'Shader', '.hlsl':'Shader',
 '.metal':'Shader', '.vsh':'Shader', '.fsh':'Shader', '.cg':'Shader', '.comp':'Shader', '.geom':'Shader', '.vp':'Shader', '.fp':'Shader',
 '.java':'Java', '.kt':'Kotlin', '.m':'Objective-C', '.mm':'Objective-C',
 '.sv':'SystemVerilog', '.svh':'SystemVerilog', '.v':'Verilog', '.vh':'Verilog',
 '.ts':'TypeScript', '.tsx':'TypeScript', '.py':'Python',
}
def lang_of(path):
    base = path.rsplit('/',1)[-1]
    if '.' not in base: return None
    ext = '.'+base.rsplit('.',1)[1]
    if base.endswith('.d.ts'): return None   # type declaration stubs
    return EXT.get(ext)
# Vendored third-party code: path regexes (case-insensitive), applied to every repo.
VENDOR = [r'(^|/)(deps|3rdparty|3rd_party|third_party|thirdparty|external|externals|vendor|extern|linux-deps|node_modules|khronos)/',
 r'(^|/)pfctoc\.h$',   # Padus DiscJuggler CDI reader SDK header (third party, shipped with its .lib / .dll)
 r'(^|/)(zlib|libpng|libzip|lzma|chdr|libchdr|xbyak|vixl|glslang|imgui|sdl2?|lua|xxhash|picotcp|libretro-common|glm|stb|miniupnpc|asio|breakpad|xxHash|vulkan-headers|volk|vma|spirv\w*|tinyxml\w*|oboe|libelf|libcue|gdbserver|nowide|dirent|json|rapidjson|glad|zstd|flac|discord|gl3w|fmt|imgui_\w+|bsd|nlohmann|cpp-httplib|sqlite3?|xbyak_aarch64|libopenmpt)/',
]
VRE = [re.compile(p, re.I) for p in VENDOR]
# per-repo extra vendored paths (prefix match on path) filled in after inspection
EXTRA = {
 'gligli_nulldc-360': [r'^gui/shaders/', r'^gui/gui/', r'^gui/utils/smb/', r'/emitter/disasm/'],
 'skmp_wren7-rtl': [r'^vendor/'],
}
def is_vendored(repo, path):
    key = repo.rstrip('/').rsplit('/',1)[-1].replace('.git','')
    for pre in EXTRA.get(key, []):
        if path.startswith(pre) or re.search(pre, path): return True
    return any(r.search(path) for r in VRE)
GEN_HDR = re.compile(rb'(?m)^[\s/*#@;!-]*(//)?\s*(this file (is|was) |file )?(auto-?|automatically |machine )?generated\b|do not edit|autogenerated', re.I)
# A data header written by a generator says so in its first line of comment text ("written by x/gen.cpp: ...",
# "tsp2_m1: gen.cpp */", "(hugepos/gen.py --tri a)"). Only that line counts: hand-written headers that merely mention a
# generator further down (ref_copies_setup.h: "the graph check (tools/gen/gen_setup_prog.cpp --check"), or say
# "written by me" (armwreck.h), stay source.
GEN_DATA = re.compile(rb'^(?:[\w.\'-]+:\s*)?(?:(?:written|made|generated|produced|emitted) by\s+\S*?\bgen\w*'
                      rb'|[\w./-]*\bgen\w*\.(?:cpp|c|py)\b(?:\s+--?\w|\s*\*/))'
                      rb'|\([\w./-]*\bgen\w*\.(?:cpp|c|py)\s+--', re.I)
def first_text_line(head):
    for ln in head.split(b'\n'):
        t = ln.strip().lstrip(b'/*#;!-@ ').strip()
        if t: return t
    return b''
# per-repo generated paths (regex)
GEN_EXTRA = {
 'gligli_nulldc-360': [r'^plugins/drkPvr/shaders\.S$', r'\.(ps|vs)\.h$'],
}
def is_generated(repo, path, size, lines, head=b''):
    key = repo.rstrip('/').rsplit('/',1)[-1].replace('.git','')
    if any(re.search(p, path) for p in GEN_EXTRA.get(key, [])): return True
    if size > 2_000_000: return True            # huge single-file tables / dumps
    base = path.rsplit('/',1)[-1].lower()
    if re.match(r'(gen|make_|mk)', base) or 'gen.' in base or 'gen_' in base: return False   # generators themselves
    if GEN_HDR.search(head): return True
    # data headers written by a generator program (test vectors, case tables)
    if base.endswith(('.h','.svh','.inc','.vh')) and GEN_DATA.search(first_text_line(head)): return True
    return False
